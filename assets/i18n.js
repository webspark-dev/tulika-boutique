let language = (() => { try { return localStorage.getItem("tulika-language") || "bn"; } catch { return "bn"; } })();
export const getLanguage = () => language;
export const t = key => copy[language][key] || key;
export const setLanguage = value => {
  language = value === "en" ? "en" : "bn";
  try { localStorage.setItem("tulika-language", language); } catch(error) { console.warn("Could not save language preference.",error); }
  document.documentElement.lang = language;
  document.querySelectorAll("[data-i18n]").forEach(node => { node.textContent = t(node.dataset.i18n); });
  document.querySelectorAll("[data-i18n-placeholder]").forEach(node => { node.placeholder = t(node.dataset.i18nPlaceholder); });
  document.querySelectorAll("[data-i18n-aria]").forEach(node => { node.setAttribute("aria-label", t(node.dataset.i18nAria)); });
  document.querySelectorAll("[data-lang-toggle]").forEach(node => { node.textContent = language === "bn" ? "EN" : "বাংলা"; });
  window.dispatchEvent(new CustomEvent("tulika:language", { detail: language }));
};

export function bilingual(bn, en) {
  return language === "bn" ? (bn || en || "") : (en || bn || "");
}

export function escapeHtml(value) {
  return String(value ?? "").replace(/[&<>"']/g, ch => ({
    "&":"&amp;", "<":"&lt;", ">":"&gt;", '"':"&quot;", "'":"&#39;"
  }[ch]));
}

export function formatINR(amount) {
  return new Intl.NumberFormat("en-IN", { style:"currency", currency:"INR", maximumFractionDigits:0 }).format(Number(amount) || 0);
}
